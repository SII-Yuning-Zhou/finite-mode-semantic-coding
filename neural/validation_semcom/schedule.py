"""Input-independent dyadic common-randomness schedules."""

from __future__ import annotations

from dataclasses import dataclass
from math import log2

import numpy as np


@dataclass(frozen=True)
class DyadicSchedule:
    """Exact mapping from fair bits to a finite mode distribution.

    Counts must sum to a power of two.  A uniform integer generated by exactly
    log2(total) fair bits is mapped through the cumulative counts.  This
    separates distribution entropy H(V), sampler consumption, and a practical
    PRNG seed.
    """

    counts: tuple[int, ...]

    def __post_init__(self) -> None:
        if not self.counts or any(count < 0 for count in self.counts):
            raise ValueError("Schedule counts must be a nonempty nonnegative tuple.")
        if sum(count > 0 for count in self.counts) == 0:
            raise ValueError("At least one mode must have positive mass.")
        total = sum(self.counts)
        if total & (total - 1):
            raise ValueError("Schedule counts must sum to a power of two.")

    @property
    def probabilities(self) -> np.ndarray:
        return np.asarray(self.counts, dtype=np.float64) / sum(self.counts)

    @property
    def entropy_bits(self) -> float:
        positive = self.probabilities[self.probabilities > 0]
        return float(-(positive * np.log2(positive)).sum())

    @property
    def fixed_width_sampler_bits_per_symbol(self) -> int:
        if sum(count > 0 for count in self.counts) == 1:
            return 0
        return int(log2(sum(self.counts)))

    def _prefix_leaves(self) -> list[tuple[int, int]]:
        """Return (depth, mode) leaves for exact fair-bit prefix sampling."""
        if sum(count > 0 for count in self.counts) == 1:
            return [(0, int(np.flatnonzero(np.asarray(self.counts) > 0)[0]))]
        denominator_bits = int(log2(sum(self.counts)))
        leaves: list[tuple[int, int]] = []
        for mode, mass in enumerate(self.counts):
            for depth in range(1, denominator_bits + 1):
                if (mass >> (denominator_bits - depth)) & 1:
                    leaves.append((depth, mode))
        if not leaves:
            raise RuntimeError("Exact prefix sampler has no leaves.")
        return sorted(leaves)

    @property
    def expected_exact_sampler_bits_per_symbol(self) -> float:
        return float(
            sum(depth * (2.0**-depth) for depth, _ in self._prefix_leaves())
        )

    def draw(self, count: int, seed: int) -> tuple[np.ndarray, np.ndarray]:
        """Draw exactly using a vectorized fixed-width fair-bit construction."""
        if count < 0:
            raise ValueError("count must be nonnegative.")
        if self.fixed_width_sampler_bits_per_symbol == 0:
            mode = int(np.flatnonzero(np.asarray(self.counts) > 0)[0])
            return np.full(count, mode, dtype=np.int64), np.zeros(count, dtype=np.uint16)
        generator = np.random.Generator(np.random.PCG64(seed))
        uniforms = generator.integers(0, sum(self.counts), size=count, dtype=np.uint16)
        cumulative = np.cumsum(self.counts)
        modes = np.searchsorted(cumulative, uniforms, side="right").astype(np.int64)
        return modes, uniforms

    def draw_exact_prefix(self, count: int, seed: int) -> tuple[np.ndarray, np.ndarray]:
        """Draw exactly from a fair-bit prefix tree and return per-draw costs.

        The leaves are the finite binary expansions of the dyadic masses. The
        resulting complete prefix tree has expected length below H(V)+2. This
        single-symbol cost remains distinct from the asymptotic block rate
        H(V), the fixed-width construction, and the practical PRNG seed size.
        """
        if count < 0:
            raise ValueError("count must be nonnegative.")
        leaves = self._prefix_leaves()
        if leaves[0][0] == 0:
            return (
                np.full(count, leaves[0][1], dtype=np.int64),
                np.zeros(count, dtype=np.uint16),
            )
        lookup: dict[tuple[int, int], int] = {}
        code = 0
        previous_depth = 0
        for depth, mode in leaves:
            code <<= depth - previous_depth
            lookup[(depth, code)] = mode
            code += 1
            previous_depth = depth

        generator = np.random.Generator(np.random.PCG64(seed))
        chunk_size = max(4096, count * 4)
        bits = generator.integers(0, 2, size=chunk_size, dtype=np.uint8)
        bit_cursor = 0

        def next_bit() -> int:
            nonlocal bits, bit_cursor
            if bit_cursor >= bits.size:
                bits = generator.integers(0, 2, size=chunk_size, dtype=np.uint8)
                bit_cursor = 0
            value = int(bits[bit_cursor])
            bit_cursor += 1
            return value

        modes = np.empty(count, dtype=np.int64)
        bit_lengths = np.empty(count, dtype=np.uint16)
        maximum_depth = max(depth for depth, _ in leaves)
        for sample in range(count):
            sample_code = 0
            for depth in range(1, maximum_depth + 1):
                sample_code = (sample_code << 1) | next_bit()
                mode = lookup.get((depth, sample_code))
                if mode is not None:
                    modes[sample] = mode
                    bit_lengths[sample] = depth
                    break
            else:
                raise RuntimeError("Fair-bit prefix tree is incomplete.")
        return modes, bit_lengths


def empirical_mutual_information(x: np.ndarray, v: np.ndarray) -> float:
    """Plug-in I(X;V) in bits for two one-dimensional discrete arrays."""
    x = np.asarray(x).reshape(-1)
    v = np.asarray(v).reshape(-1)
    if x.size != v.size:
        raise ValueError("x and v must have equal length.")
    if x.size == 0:
        return 0.0
    _, x_index = np.unique(x, return_inverse=True)
    _, v_index = np.unique(v, return_inverse=True)
    joint = np.zeros((x_index.max() + 1, v_index.max() + 1), dtype=np.float64)
    np.add.at(joint, (x_index, v_index), 1.0)
    joint /= x.size
    px = joint.sum(axis=1, keepdims=True)
    pv = joint.sum(axis=0, keepdims=True)
    mask = joint > 0
    product = px @ pv
    return float(np.sum(joint[mask] * np.log2(joint[mask] / product[mask])))
